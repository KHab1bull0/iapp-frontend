/**
 * The five categories every new user gets are stored by their English names;
 * show them in the chosen language. Categories the user made or renamed are
 * shown as they are.
 */
const DEFAULT_CATEGORY_NAMES: Record<string, Record<Lang, string>> = {
  Salary: { uz: 'Maosh', en: 'Salary' },
  Freelance: { uz: 'Frilans', en: 'Freelance' },
  'Food & Dining': { uz: 'Oziq-ovqat', en: 'Food & Dining' },
  Transport: { uz: 'Transport', en: 'Transport' },
  Entertainment: { uz: "Ko'ngilochar", en: 'Entertainment' },
}

export function categoryName(name: string, lang: Lang): string {
  return DEFAULT_CATEGORY_NAMES[name]?.[lang] ?? name
}

export function useCategoryName(): (name: string) => string {
  const { lang } = useLang()
  return (name) => categoryName(name, lang)
}
