/** The seeded starting level is stored as "New"; show it in the chosen language unless renamed. */
export function levelName(level: Pick<Level, 'name' | 'locked'>, lang: Lang): string {
  return level.locked && level.name === 'New' ? englishMessages[lang].newLevel : level.name
}

export function useLevelName(): (level: Pick<Level, 'name' | 'locked'>) => string {
  const { lang } = useLang()
  return (level) => levelName(level, lang)
}
