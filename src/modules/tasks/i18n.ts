const UZ_UNIT: Record<RepeatUnit, string> = { day: 'kun', week: 'hafta', month: 'oy' }
const enUnit = (n: number, unit: RepeatUnit) => `${n} ${unit}${n === 1 ? '' : 's'}`

const enOrdinal = (n: number) => {
  const tens = n % 100
  if (tens >= 11 && tens <= 13) return `${n}th`
  return `${n}${['th', 'st', 'nd', 'rd'][n % 10] ?? 'th'}`
}

